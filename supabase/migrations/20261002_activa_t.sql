-- Activa’t independent Supabase schema and Sites data migration.
-- Every object is prefixed activa_t_ so the existing Activa app is untouched.
create schema if not exists activa_t_private;

create table if not exists public.activa_t_activities (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  legacy_id bigint,
  type text not null,
  activity_date date not null,
  start_time text,
  status text not null default 'scheduled' check (status in ('scheduled', 'completed', 'cancelled')),
  ever_cancelled boolean not null default false,
  ever_completed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, legacy_id)
);

create table if not exists public.activa_t_weights (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  legacy_id bigint,
  weight numeric(5,2) not null check (weight > 0 and weight < 500),
  measured_at date not null,
  created_at timestamptz not null default now(),
  unique (user_id, legacy_id)
);

create table if not exists public.activa_t_activity_types (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  icon_key text not null default 'sparkles',
  color text not null default '#65a84f',
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create index if not exists activa_t_activities_user_date_idx on public.activa_t_activities (user_id, activity_date desc);
create index if not exists activa_t_weights_user_date_idx on public.activa_t_weights (user_id, measured_at desc);

alter table public.activa_t_activities enable row level security;
alter table public.activa_t_weights enable row level security;
alter table public.activa_t_activity_types enable row level security;

drop policy if exists "activa_t_activities_owner" on public.activa_t_activities;
create policy "activa_t_activities_owner" on public.activa_t_activities
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "activa_t_weights_owner" on public.activa_t_weights;
create policy "activa_t_weights_owner" on public.activa_t_weights
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "activa_t_activity_types_owner" on public.activa_t_activity_types;
create policy "activa_t_activity_types_owner" on public.activa_t_activity_types
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.activa_t_activities to authenticated;
grant select, insert, update, delete on public.activa_t_weights to authenticated;
grant select, insert, update, delete on public.activa_t_activity_types to authenticated;
grant usage, select on all sequences in schema public to authenticated;

