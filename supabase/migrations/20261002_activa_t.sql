drop function if exists activa_t_private.on_user_created();
create or replace function activa_t_private.on_user_created()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if lower(coalesce(new.email, '')) = 'anna.batet.soler@gmail.com' then
    perform activa_t_private.seed_anna(new.id);
  end if;
  return new;
end;
$$;
revoke all on function activa_t_private.on_user_created() from public, anon, authenticated;

drop trigger if exists activa_t_seed_anna on auth.users;
create trigger activa_t_seed_anna
after insert on auth.users
for each row execute function activa_t_private.on_user_created();

-- Also seed Anna if her Google account already exists when this migration runs.
do $$
declare
  anna_id uuid;
begin
  select id into anna_id from auth.users where lower(email) = 'anna.batet.soler@gmail.com' limit 1;
  if anna_id is not null then perform activa_t_private.seed_anna(anna_id); end if;
end;
$$;
